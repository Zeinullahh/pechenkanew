// Re-run explicitly after reviewing upstream visual changes; not a build dependency.
// node scripts/generate-sandbox-reference.mjs /path/to/webmail-v2/frontend/app/globals.css
import fs from "node:fs";
import crypto from "node:crypto";
import path from "node:path";
import postcss from "postcss";
const source = process.argv[2];
if (!source) throw new Error("Pass the reference globals.css path.");
const css = fs.readFileSync(source, "utf8");
const root = postcss.parse(css);
const scope = ".silence-sandbox .sandbox-webmail";
const relevant =
  /\.(?:dashboard-[\w-]+|topbar-[\w-]+|brand-[\w-]+|glass(?:-[\w-]+)?|sidebar(?:-[\w-]+)?|folder-[\w-]+|status-[\w-]+|email-[\w-]+|unread-[\w-]+|total-count|sender-[\w-]+|attachments?(?:-[\w-]+)?|security-badge|glow-[\w-]+|send-email-button|compose-cta|app-container|search-(?:bar|input|icon)|clear-search)(?![\w-])/;
const keyframes = new Set();
root.walkRules((rule) => {
  if (rule.parent.type === "atrule" && /keyframes/.test(rule.parent.name))
    return;
  const selectors = rule.selectors.filter(
    (selector) =>
      selector === ":root" ||
      selector === '[data-theme="light"]' ||
      selector === "body.light" ||
      relevant.test(selector),
  );
  if (!selectors.length) {
    rule.remove();
    return;
  }
  rule.selectors = selectors.map((selector) => {
    if (selector === ":root") return scope;
    if (selector.startsWith("body.light"))
      return selector.replace("body.light", `${scope}[data-theme="light"]`);
    if (selector.startsWith("[data-theme=")) return `${scope}${selector}`;
    if (/^(html|body)/.test(selector))
      return `${scope} ${selector.replace(/^(html|body)(?:\.[\w-]+)?\s*/, "")}`;
    return `${scope} ${selector}`;
  });
  rule.walkDecls(/^animation/, (decl) => {
    for (const word of decl.value.match(/[a-zA-Z][\w-]*/g) || [])
      keyframes.add(word);
  });
});
root.walkAtRules((at) => {
  if (/keyframes/.test(at.name) && !keyframes.has(at.params)) at.remove();
  // The product runs in a 1384px desktop canvas. Mobile uses the frame's scroll viewport.
  if (at.name === "media") {
    const max = at.params.match(/max-width:\s*([\d.]+)px/);
    const min = at.params.match(/min-width:\s*([\d.]+)px/);
    if ((max && +max[1] < 1384) || (min && +min[1] > 1384)) at.remove();
  }
  if (["tailwind", "import", "font-face"].includes(at.name)) at.remove();
});
root.walkComments((comment) => comment.remove());
root.walkAtRules((at) => {
  if (at.nodes && !at.nodes.length) at.remove();
});
// Animation names are global even when selectors are scoped.
const animationNames = new Set();
root.walkAtRules(/keyframes/, (at) => {
  animationNames.add(at.params);
  at.params = `sb-ref-${at.params}`;
});
root.walkDecls(/^animation/, (decl) => {
  decl.value = decl.value.replace(/[a-zA-Z][\w-]*/g, (word) =>
    animationNames.has(word) ? `sb-ref-${word}` : word,
  );
});
const header = `/* Adapted verbatim declarations from webmail-v2/frontend/app/globals.css.\n * Source SHA-256: ${crypto.createHash("sha256").update(css).digest("hex")}\n * Selectors are scoped to the sandbox; unrelated screens and narrow viewport rules are omitted.\n * Regenerate with scripts/generate-sandbox-reference.mjs; embed-specific rules live in sandbox.css.\n */\n`;
fs.writeFileSync(
  "src/components/sandbox/webmail-reference.css",
  header + root.toString(),
);
// Embed the original bitmap unchanged so resetting an offline demo needs no asset request.
const logo = fs.readFileSync(
  path.join(path.dirname(source), "../public/logo-slnc.png"),
);
fs.writeFileSync(
  "src/components/sandbox/brandAsset.js",
  `// Original public/logo-slnc.png, embedded unchanged for offline use. Generated by generate-sandbox-reference.mjs.\nexport const SLNC_LOGO = 'data:image/png;base64,${logo.toString("base64")}';\n`,
);
